#ifndef BOARD_PINS_H
#define BOARD_PINS_H

#include "n32h47x_48x_gpio.h"

/* MC-S001 上控板：LED501 蓝灯，PB2 低电平点亮。 */
#define BOARD_LED_PORT GPIOB
#define BOARD_LED_PIN GPIO_PIN_2
#define BOARD_LED_ACTIVE_LOW 1

/* CN501 调试接口：1 GND，2 RX，3 TX，4 MCU 3.3V。 */
#define BOARD_DEBUG_UART USART2
#define BOARD_DEBUG_UART_PORT GPIOA
#define BOARD_DEBUG_UART_TX_PIN GPIO_PIN_2
#define BOARD_DEBUG_UART_RX_PIN GPIO_PIN_3
#define BOARD_DEBUG_UART_TX_AF GPIO_AF_USART2_TX_PA2
#define BOARD_DEBUG_UART_RX_AF GPIO_AF_USART2_RX_PA3

/* LCD：GPIO模拟9位SPI，时钟空闲高，下降沿更新、上升沿采样。 */
#define BOARD_LCD_BUS_PORT GPIOA
#define BOARD_LCD_CS_PIN GPIO_PIN_4
#define BOARD_LCD_CLOCK_PIN GPIO_PIN_5
#define BOARD_LCD_DATA_PIN GPIO_PIN_7
#define BOARD_LCD_RESET_PORT GPIOC
#define BOARD_LCD_RESET_PIN GPIO_PIN_15
#define BOARD_LCD_BACKLIGHT_PORT GPIOB
#define BOARD_LCD_BACKLIGHT_PIN GPIO_PIN_5

/* GPIO 时钟、推挽/无上下拉/慢速配置由 N32Cube GPIO_Configuration() 完成。 */

#endif
