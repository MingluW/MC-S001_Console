/* 旧lcdfont.c逐段Lcd_code表：同一字节中PH共用，K/M分别选择。 */
#define LCD_SPEED_UNIT_BYTE 12u
#define LCD_SPEED_PH_MASK 0x02u
#define LCD_SPEED_M_MASK 0x04u
#define LCD_SPEED_K_MASK 0x08u

static void add_segments(uint8_t *frame, const uint8_t *segments)
{
    for (size_t i = 0u; i < LCD_FRAME_BYTES; ++i)
    {
        frame[i] |= segments[i];
    }
}

bool LcdSegments_BuildSpeed(uint16_t speed_x10, LcdSpeedUnit unit,
                           uint8_t frame[LCD_FRAME_BYTES])
{
    if ((frame == NULL) || (speed_x10 > 9999u) ||
        ((unit != LCD_SPEED_UNIT_KPH) && (unit != LCD_SPEED_UNIT_MPH)))
    {
        return false;
    }
    memset(frame, 0, LCD_FRAME_BYTES);
    add_segments(frame, speed_icon);
    frame[LCD_SPEED_UNIT_BYTE] |= LCD_SPEED_PH_MASK |
        ((unit == LCD_SPEED_UNIT_KPH) ? LCD_SPEED_K_MASK : LCD_SPEED_M_MASK);
    add_segments(frame, decimal_point);
    /* 整数高位消隐，个位和小数位始终显示，例如0 -> 0.0，125 -> 12.5。 */
    if (speed_x10 >= 1000u)
    {
        add_segments(frame, digit_1[speed_x10 / 1000u]);
    }
    if (speed_x10 >= 100u)
    {
        add_segments(frame, digit_2[(speed_x10 / 100u) % 10u]);
    }
    add_segments(frame, digit_3[(speed_x10 / 10u) % 10u]);
    add_segments(frame, digit_4[speed_x10 % 10u]);
    return true;
}

