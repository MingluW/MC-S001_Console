bool LcdSegments_BuildDigits(uint16_t value, bool pad_zero, uint8_t frame[LCD_FRAME_BYTES])
{
    if ((frame == NULL) || (value > 9999u))
    {
        return false;
    }
    memset(frame, 0, LCD_FRAME_BYTES);
    if (pad_zero || (value >= 1000u))
    {
        add_segments(frame, digit_1[value / 1000u]);
    }
    if (pad_zero || (value >= 100u))
    {
        add_segments(frame, digit_2[(value / 100u) % 10u]);
    }
    if (pad_zero || (value >= 10u))
    {
        add_segments(frame, digit_3[(value / 10u) % 10u]);
    }
    add_segments(frame, digit_4[value % 10u]);
    return true;
}

bool LcdSegments_BuildIncline(uint16_t value, uint8_t frame[LCD_FRAME_BYTES])
{
    if (!LcdSegments_BuildDigits(value, false, frame))
    {
        return false;
    }
    add_segments(frame, grade_icon);
    return true;
}

bool LcdSegments_BuildStopped(uint8_t frame[LCD_FRAME_BYTES])
{
    if (frame == NULL)
    {
        return false;
    }
    memset(frame, 0, LCD_FRAME_BYTES);
    for (size_t i = 0u; i < 4u; ++i)
    {
        add_segments(frame, minus_segments[i]);
    }
    return true;
}
